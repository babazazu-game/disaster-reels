/**
 * Чёткость картинки и читаемость интерфейса на экранах любой плотности.
 *
 * Модуль движко-независимый намеренно: и Phaser, и Three.js упираются в одну
 * и ту же арифметику — сколько физических пикселей приходится на пиксель
 * вёрстки и насколько мелким при этом становится текст.
 *
 * ── ЧТО ЗА ПРОБЛЕМА ─────────────────────────────────────────────────────
 *
 * Движок по умолчанию делает холст в CSS-пикселях: `canvas.width` равен
 * ширине родителя в вёрстке. На телефоне с `devicePixelRatio` 3 это втрое
 * меньше физического разрешения экрана, и браузер растягивает готовую
 * картинку обратно. Мылится ВСЁ разом — и текст, и спрайты, и модели, —
 * сколько бы ни было пикселей в самих текстурах.
 *
 * Лечится это одинаково везде: холст делается в ФИЗИЧЕСКИХ пикселях
 * (`css * dpr`), а показывается в CSS-размере. Дальше движки расходятся —
 * у Phaser это `Scale.NONE` + `zoom = 1/dpr`, у Three.js
 * `renderer.setPixelRatio()`, — но число `dpr` им нужно одно и то же,
 * и берут они его отсюда.
 *
 * ── ПОТОЛОК ПЛОТНОСТИ ───────────────────────────────────────────────────
 *
 * Пикселей приходится закрашивать в dpr² раз больше, и это главный расход
 * кадра. Тройка вместо двойки добавляет ещё 2.25 раза сверху ради разницы,
 * которую на телефоне уже не видно, — на этом в прошлой игре просела частота
 * кадров. Поэтому режем на двойке.
 */

export const MAX_PIXEL_RATIO = 2;

/**
 * Отладочные параметры работают ТОЛЬКО при локальной разработке.
 *
 * На площадке домен чужой, и `?dpr=` с `?fps=` там не включаются никаким
 * адресом. Так счётчик кадров и переключатель плотности физически не могут
 * оказаться в боевой сборке, даже если параметр случайно попадёт в ссылку.
 */
export function debugAllowed(): boolean {
  try {
    const host = window.location.hostname || '';
    return host === 'localhost' || host === '127.0.0.1' || host === ''
      || /^192\.168\./.test(host) || /^10\./.test(host)
      || /^172\.(1[6-9]|2\d|3[01])\./.test(host);
  } catch {
    return false;
  }
}

/** Значение отладочного параметра из адреса — или `null`, если он запрещён. */
export function debugFlag(name: string): string | null {
  if (!debugAllowed()) return null;
  try {
    return new URLSearchParams(window.location.search).get(name);
  } catch {
    return null;
  }
}

/**
 * Плотность, навязанная через `?dpr=` — для замеров на живом устройстве.
 *
 * Потолок для неё СВОЙ и выше обычного: смысл параметра как раз в том, чтобы
 * сравнить единицу, двойку и тройку и увидеть, где кончается прирост чёткости
 * и начинается просадка кадров. Общий потолок это сравнение бы и обрезал.
 */
function requestedRatio(): number | null {
  const asked = Number(debugFlag('dpr'));
  return Number.isFinite(asked) && asked > 0 ? Math.min(asked, 4) : null;
}

/** Во сколько раз холст должен быть подробнее своего размера в вёрстке. */
export function pixelRatio(): number {
  const forced = requestedRatio();
  if (forced !== null) return Math.max(1, forced);

  const dpr = typeof window === 'undefined' ? 1 : window.devicePixelRatio || 1;
  return Math.max(1, Math.min(dpr, MAX_PIXEL_RATIO));
}

/** Сколько пикселей холста приходится на один физический (CSS) пиксель экрана. */
export const cssPx = (px: number): number => px * pixelRatio();

/**
 * Нижний предел кегля — в физических пикселях экрана.
 *
 * Площадка требует не мельче 12 (статистика — 11). Тринадцать взяты с запасом
 * на округление и на то, что кегль не равен высоте видимых букв.
 */
export const MIN_TEXT_PX = 13;

/**
 * Кегль в пикселях холста, но НЕ МЕЛЬЧЕ читаемого предела.
 *
 * Интерфейс в играх верстается от высоты экрана: `u = H / базовая высота`.
 * На мониторе это работает, а у телефона В ЛАНДШАФТЕ высота всего 360–430
 * CSS-пикселей, и `u` падает до трети. Основной текст окна превращался
 * в 9 физических пикселей — мельче разрешённого минимума и просто нечитаемо.
 *
 * ВАЖНО, ЧТО ПРЕДЕЛ ПОЭЛЕМЕНТНЫЙ. Первая попытка в «МикроБуме» подняла общую
 * единицу интерфейса, и вместе с мелким текстом раздулось ВСЁ: заголовки,
 * кнопки, плашки, — окна перестали помещаться на экран. Поднимать надо ровно
 * то, что провалилось ниже предела: крупный заголовок и на телефоне читается
 * прекрасно, трогать его незачем.
 *
 * Поэтому коробки, отступы и вся раскладка остаются на обычном `u`, а сюда
 * приходит только размер шрифта.
 */
export function fontPx(units: number, u: number): number {
  return Math.max(units * u, cssPx(MIN_TEXT_PX));
}

/**
 * Размер зоны нажатия — не меньше 44 физических пикселей (п. 1.8).
 *
 * Растёт ЗОНА, а не сама кнопка. Требование про 44 пикселя — про попадание
 * пальцем, а не про то, каким рисовать кружок; раздувать ради него ещё и
 * картинку значит ломать раскладку там, где она была в порядке.
 */
export function tapSize(size: number): number {
  return Math.max(size, cssPx(44));
}

/**
 * Счётчик кадров для замеров на ЖИВОМ устройстве: `?fps=1` в адресе.
 *
 * Нужен, чтобы сравнивать плотность по числам, а не по ощущению. Открыть
 * `?fps=1&dpr=1`, потом `&dpr=2`, потом `&dpr=3` и посмотреть, где падает
 * частота и где перестаёт расти чёткость. Показывает и худшее значение
 * за сессию: средняя частота молчит о рывках, а видны как раз они.
 *
 * Частоту меряет сам, по `requestAnimationFrame`, а не спрашивает у движка:
 * так один и тот же счётчик работает и в Phaser, и в Three.js, и в игре
 * вообще без движка. Ничего не создаёт, пока параметр не передан.
 */
export function showFpsMeter(details?: () => string): () => void {
  if (!debugFlag('fps')) return () => undefined;

  const box = document.createElement('div');
  box.style.cssText = 'position:fixed;left:6px;top:6px;z-index:9999;padding:4px 8px;'
    + 'font:600 13px/1.3 monospace;color:#fff;background:rgba(0,0,0,.6);'
    + 'border-radius:6px;pointer-events:none;white-space:pre';
  document.body.appendChild(box);

  let frames = 0;
  let since = performance.now();
  let worst = Infinity;
  let raf = 0;

  const tick = (): void => {
    frames++;
    const now = performance.now();
    if (now - since >= 500) {
      const fps = (frames * 1000) / (now - since);
      if (fps > 0 && fps < worst) worst = fps;
      box.textContent = `FPS ${fps.toFixed(0)}  мин ${worst === Infinity ? '—' : worst.toFixed(0)}`
        + `\nDPR ${pixelRatio()}`
        + (details ? `  ${details()}` : '');
      frames = 0;
      since = now;
    }
    raf = requestAnimationFrame(tick);
  };
  raf = requestAnimationFrame(tick);

  return () => {
    cancelAnimationFrame(raf);
    box.remove();
  };
}

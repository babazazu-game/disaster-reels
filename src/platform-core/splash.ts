/**
 * Экран загрузки.
 *
 * Живёт в РАЗМЕТКЕ, а не внутри движка, и на то есть причина: показать его
 * надо раньше самого движка. Порядок запуска всегда один — дождаться SDK
 * (язык нужен до первого кадра, п. 2.14), поднять движок, загрузить ассеты.
 * Первые две трети этого времени рисовать физически нечем: ни сцены, ни
 * рендерера ещё нет. На телефоне отсюда и берётся «просто пустой фон»
 * на несколько секунд, за который прилетает замечание.
 *
 * Этот модуль — только ручки управления. Разметку и оформление брать из
 * `boot/splash.html`: там же лежит и разбор, почему в стилях документа
 * стоит именно это.
 *
 * Ожидаемые узлы: `#splash`, `#splash-fill`, `#splash-text` и класс `done`
 * на `#splash` для гашения.
 */

const el = <T extends HTMLElement>(id: string): T | null =>
  document.getElementById(id) as T | null;

/**
 * Полоса. `0..1`.
 *
 * Прогресс делится на две части: пока идёт ожидание SDK и шрифтов, полоса
 * доходит до трети — точное число там неоткуда взять, но неподвижная полоса
 * читается как зависшая игра. Оставшиеся две трети отдаёт загрузчик ассетов,
 * и вот они уже честные.
 */
export function splashProgress(value: number): void {
  const fill = el<HTMLDivElement>('splash-fill');
  if (fill) fill.style.width = `${Math.max(0, Math.min(1, value)) * 100}%`;
}

/**
 * Подпись под полосой.
 *
 * До того как язык известен, подписи нет вовсе. Написать сначала не на том
 * языке, а через секунду переписать — ровно то, за что площадка делает
 * замечание по п. 2.14, и на загрузочном экране это заметнее всего.
 */
export function splashCaption(text: string): void {
  const node = el('splash-text');
  if (node) node.textContent = text;
}

/**
 * Убрать экран.
 *
 * Сначала гасим прозрачностью, потом выкидываем из документа: резкая подмена
 * читается как мигание, а оставлять невидимый слой поверх холста нельзя —
 * он бы съедал касания.
 */
export function splashHide(): void {
  const node = el('splash');
  if (!node) return;
  splashProgress(1);
  node.classList.add('done');
  const drop = (): void => node.remove();
  node.addEventListener('transitionend', drop, { once: true });
  // Если переход почему-то не случится (вкладка в фоне — анимации не идут),
  // экран всё равно обязан уйти.
  setTimeout(drop, 600);
}

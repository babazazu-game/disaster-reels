/**
 * Гашение системного медиаплеера.
 *
 * ЧТО ЗА ПРОБЛЕМА. Долгий звук браузер считает «музыкой, которую слушают»:
 * на телефоне в шторке появляется панель проигрывателя с названием вкладки
 * и кнопками, на десктопе — значок ноты в адресной строке. Для площадки это
 * нарушение (пп. 1.6.1.6 и 1.6.2.5): игра не должна выглядеть плеером.
 *
 * Web Audio сам по себе НЕ спасает, хотя об этом часто пишут. Проверено на
 * «МикроБуме»: музыка шла через `AudioContext`, тегов `<audio>` в игре не было
 * вовсе — а панель на Android всё равно появлялась. Chrome заводит медиасессию
 * по факту длительного воспроизведения, независимо от того, чем оно сделано.
 *
 * Поэтому сессию гасим явно. Снимаем и обработчики действий: пока на плеере
 * висит хоть один, браузер считает, что игра плеером управляет, и панель
 * держится.
 *
 * ПОЧЕМУ НЕ ОДИН РАЗ. Сессия заводится не в момент вызова `play()`, а спустя
 * несколько секунд непрерывного звука, — единственный вызов на старте трека
 * просто не застаёт её. Отсюда серия повторов: она укладывается в окно,
 * когда браузер её создаёт, и стоит три присваивания.
 */

/** Действия, которые браузер предлагает повесить на панель плеера. */
const ACTIONS: MediaSessionAction[] = [
  'play', 'pause', 'stop', 'seekbackward', 'seekforward', 'seekto',
  'previoustrack', 'nexttrack',
];

/** Когда повторить гашение после запуска трека, мс. */
const RETRIES = [0, 600, 2000, 5000, 9000];

function silenceOnce(): void {
  const session = typeof navigator === 'undefined' ? null : navigator.mediaSession;
  if (!session) return;

  try {
    session.metadata = null;
    session.playbackState = 'none';
  } catch {
    // Старый браузер без части полей — не повод падать.
  }

  for (const action of ACTIONS) {
    try {
      session.setActionHandler(action, null);
    } catch {
      // Действие не поддерживается этим браузером — пропускаем.
    }
  }
}

export function silenceMediaSession(): void {
  for (const delay of RETRIES) {
    if (delay === 0) silenceOnce();
    else setTimeout(silenceOnce, delay);
  }
}
